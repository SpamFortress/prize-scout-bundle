/** Slots for an official rate. `officialRate` stays empty until a published source fills it. A number without `source` is ignored. */

export interface StateTaxSlot {
  code: string;
  name: string;
  /** Decimal rate copied from an official publication. Null until that publication is loaded. */
  officialRate: number | null;
  /** Citation for `officialRate`. Required before the rate is used. */
  source: string | null;
}

